"""Terraform emitters: neutral model -> Terraform configuration (HCL) for the AWS, Azure and Google provider.

Design rules:

* What is written is what the AWS, Azure and gcp emitters write (the same groups, rules and priorities), as Terraform
  resources instead of CLI calls or a template. What those emitters say about how the cloud decides holds here.
* terraform-aws: ``aws_security_group`` per group, without members, and one ``aws_vpc_security_group_ingress_rule``
  or ``_egress_rule`` per address block and service (the resources AWS counts as rules). Terraform takes away the
  outbound rule AWS gives a new group, so a group allows outbound what its egress resources allow and nothing else.
  The VPC is a variable; which network interfaces get which group is a comment and an output.
* terraform-azure: ``azurerm_network_security_group`` per group with its rules inline. Application security groups
  given by name are data sources in the resource group deployed to. The networks of each group (the subnets to
  associate it with) are a comment and an output.
* terraform-google: one ``google_compute_network_firewall_policy`` with a ``_rule`` resource per rule of the gcp
  emitter. The project is a variable; the association with a network is a comment, to write once the rules are checked.
* New resources only: ``terraform apply`` refuses a group that exists (AWS: a group of the same name in the VPC;
  Azure: a resource that is not in the state), so nothing that exists is changed.
* Text is written as HCL strings: escaped, with ``${`` and ``%{`` doubled, so that nothing in it is an expression.
"""

