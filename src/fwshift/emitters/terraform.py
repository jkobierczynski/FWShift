AWS_PROVIDER = ">= 5.0"  # aws_vpc_security_group_ingress_rule and _egress_rule
AZURE_PROVIDER = ">= 3.0"
_IDENTIFIER = re.compile(r"[^A-Za-z0-9_-]+")


# -- HCL ---------------------------------------------------------------------------------------


def string(text: str) -> str:
    """An HCL string literal that holds ``text`` and nothing that Terraform works out."""
    out = []
    for char in str(text):
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif ord(char) < 0x20 or ord(char) == 0x7F or 0x80 <= ord(char) < 0xA0 or char in "  ":
            out.append(f"\\u{ord(char):04x}")
        else:
            out.append(char)
    return '"' + "".join(out).replace("${", "$${").replace("%{", "%%{") + '"'


def value(item: Any) -> str:
    if isinstance(item, bool):
        return "true" if item else "false"
    if isinstance(item, int):
        return str(item)
    if isinstance(item, (list, tuple)):
        return "[" + ", ".join(value(i) for i in item) + "]"
    return string(str(item))


def identifier(text: str, taken: Set[str], prefix: str = "r") -> str:
    """A name for a resource: letters, digits, '_' and '-', starting with a letter; unique in ``taken``."""
    base = _IDENTIFIER.sub("_", text).strip("_-")[:60] or prefix
    if not re.match(r"[A-Za-z_]", base):
        base = f"{prefix}_{base}"
    candidate, counter = base, 2
    while candidate.lower() in taken:
        candidate = f"{base}_{counter}"
        counter += 1
    taken.add(candidate.lower())
    return candidate


def comment(text: str) -> str:
    """One line of a comment: no line breaks in it."""
    return "# " + re.sub(r"[\x00-\x1f\x7f  ]", " ", text)


def block(header: str, lines: Sequence[str], indent: str = "") -> List[str]:
    return [f"{indent}{header} {{"] + [f"{indent}  {line}" if line else "" for line in lines] + [f"{indent}}}"]


def attributes(pairs: Sequence[Tuple[str, str]]) -> List[str]:
    """``name = value`` lines, aligned."""
    width = max((len(name) for name, _ in pairs), default=0)
    return [f"{name.ljust(width)} = {text}" for name, text in pairs]


def header(platform: str, lines: Sequence[str]) -> List[str]:
    return [comment(f"Generated by FWShift: {platform}, as Terraform configuration."),
            comment("Read the report first: what is not written is listed there."), "#"] + [comment(line) if line else "#" for line in lines]  # fmt: skip


# -- AWS ---------------------------------------------------------------------------------------


def emit_terraform_aws(policy: Policy, report: Report, options: Options) -> str:
    return _AwsEmitter(emit_aws.prepare(policy, report, options), report, options, transform.rule_zones(policy)).run()


class _AwsEmitter(emit_aws._Emitter):  # pylint: disable=protected-access
    def _script(self, groups: List[emit_aws._Group]) -> str:
        out = header("AWS EC2 security groups for one VPC (hashicorp/aws)", [
            "  terraform init",
            "  terraform plan -var vpc_id=vpc-...      shows what would be created",
            "  terraform apply -var vpc_id=vpc-...     creates the groups and their rules",
            "",
            "The groups are created WITHOUT members: nothing changes for any traffic until they are attached. Attach each",
            "group to the network interfaces whose private addresses are listed above it (# attach ...): an interface gets",
            "every group whose list holds one of its addresses, and then no other groups. A group of the same name in the",
            "VPC makes the apply fail; nothing that exists is changed. Terraform takes away the outbound rule AWS gives a",
            "new group: a group allows outbound what its egress rules below allow, and nothing else.",
        ])
        out += [""] + block("terraform", ["required_version = \">= 1.3\""] + block("required_providers", block("aws =", attributes([
            ("source", string("hashicorp/aws")), ("version", string(AWS_PROVIDER))]))))  # fmt: skip
        out += [""] + block('variable "vpc_id"', attributes([("description", string("The VPC to create the security groups in (vpc-...)")),
                                                              ("type", "string")]))  # fmt: skip
        taken: Set[str] = set()
        names: Dict[str, str] = {}
        for group in groups:
            names[group.var] = identifier(group.var.lower(), taken, "g")
        for group in groups:
            attach = " ".join(interval_text(i) for i in group.attach)
            short = attach if len(attach) <= 160 else attach[:150].rsplit(" ", 1)[0] + " ..."
            resource = names[group.var]
            out += ["", comment(f"attach {group.name}: {attach}")]
            out += block(f'resource "aws_security_group" "{resource}"', attributes([
                ("name", string(group.name)), ("description", string(emit_aws._description(f"FWShift: for the interfaces of {short}"))),
                ("vpc_id", "var.vpc_id")]) + block("tags =", [f"fwshift = {string('generated')}"]))  # fmt: skip
        for group in groups:
            resource = names[group.var]
            for word, entries, rules in (("ingress", group.inbound, group.rules_in), ("egress", group.outbound, group.rules_out)):
                number = 0
                for (version, perm) in sorted(entries, key=lambda k: (k[0], emit_aws._perm_key(k[1]))):
                    description = emit_aws._description("FWShift: " + ", ".join(dict.fromkeys(rules[(version, perm)])))
                    for interval in entries[(version, perm)]:
                        for cidr in emit_aws._cidrs(interval):
                            number += 1
                            pairs: List[Tuple[str, str]] = [("security_group_id", f"aws_security_group.{resource}.id"), ("ip_protocol", string(perm[0]))]
                            if perm[0] in ("tcp", "udp", "icmp", "icmpv6"):
                                pairs += [("from_port", str(perm[1])), ("to_port", str(perm[2]))]
                            pairs += [("cidr_ipv4" if version == 4 else "cidr_ipv6", string(cidr)), ("description", string(description))]
                            name = f"{resource}_{'in' if word == 'ingress' else 'out'}_{number}"
                            out += [""] + block(f'resource "aws_vpc_security_group_{word}_rule" "{name}"', attributes(pairs))
        out += [""] + block('output "fwshift_attach"', [f"description = {string('Each security group, with the private addresses of the network interfaces to attach it to')}"]
                            + block("value =", [line for group in groups for line in block(f"{string(group.name)} =", attributes([
                                ("id", f"aws_security_group.{names[group.var]}.id"),
                                ("addresses", value([interval_text(i) for i in group.attach]))]))]))  # fmt: skip
        if self.comments:
            out += ["", "# Not written:"] + [comment(f"  {line}") for line in self.comments]
        return "\n".join(out) + "\n"

    def _notes(self, groups: List[emit_aws._Group]) -> None:
        super()._notes(groups)
        self.report.retract("note", {"AWS_LOAD", "AWS_ATTACH"})
        self.report.note(
            Severity.REVIEW, "TERRAFORM_LOAD",
            "the output is Terraform configuration (section 10): terraform plan -var vpc_id=... shows what it creates, terraform "
            "apply creates new security groups and their rules; a group of the same name in the VPC makes it fail. The groups "
            "have no members when it is done: nothing changes until they are attached",
        )  # fmt: skip
        if groups:
            self.report.note(
                Severity.REVIEW, "TERRAFORM_ATTACH",
                f"{len(groups)} group{'' if len(groups) == 1 else 's'}: attach each to the network interfaces whose private addresses "
                "its '# attach' comment (and the output fwshift_attach) lists, and take the other groups off those interfaces: "
                "vpc_security_group_ids of the instances, security_groups of the network interfaces, or "
                "aws_network_interface_sg_attachment. A group applies to the whole interface: give the addresses of one "
                "interface the same group",
            )  # fmt: skip


# -- Azure -------------------------------------------------------------------------------------

_AZURE_FIELDS = (
    ("priority", "priority"), ("direction", "direction"), ("access", "access"), ("protocol", "protocol"),
    ("sourcePortRange", "source_port_range"), ("sourcePortRanges", "source_port_ranges"),
    ("destinationPortRange", "destination_port_range"), ("destinationPortRanges", "destination_port_ranges"),
    ("sourceAddressPrefix", "source_address_prefix"), ("sourceAddressPrefixes", "source_address_prefixes"),
    ("destinationAddressPrefix", "destination_address_prefix"), ("destinationAddressPrefixes", "destination_address_prefixes"),
    ("description", "description"),
)  # fmt: skip
_RESOURCE_ID = re.compile(r"^\[resourceId\('Microsoft\.Network/applicationSecurityGroups', '((?:[^']|'')*)'\)\]$")


def emit_terraform_azure(policy: Policy, report: Report, options: Options) -> str:
    template = json.loads(emit_azure.emit(policy, report, options))
    report.retract("note", {"AZURE_LOAD"})
    report.note(
        Severity.REVIEW, "TERRAFORM_LOAD",
        "the output is Terraform configuration (section 10): terraform plan -var resource_group_name=... shows what it creates, "
        "terraform apply creates new network security groups with their rules; a group of the same name in the resource group "
        "makes it fail (it is not in the state). Then associate each group with the subnets of its networks (the comments and "
        "the output fwshift_networks), with azurerm_subnet_network_security_group_association",
    )  # fmt: skip
    metadata = template.get("metadata", {})
    networks: Dict[str, List[str]] = metadata.get("networks", {})
    out = header("Azure network security groups (hashicorp/azurerm)", [
        "  terraform init",
        "  terraform plan -var resource_group_name=...     shows what would be created (with -var subscription_id=...,",
        "                                                  or ARM_SUBSCRIPTION_ID in the environment, for azurerm 4 and later)",
        "  terraform apply -var resource_group_name=...    creates the groups and their rules",
        "",
        "The groups are associated with nothing: associate each with the subnets of the networks listed above it",
        "(azurerm_subnet_network_security_group_association). A group of the same name in the resource group makes the",
        "apply fail; nothing that exists is changed. Each list ends in the default of the source, before Azure's own.",
    ])
    out += [""] + block("terraform", ["required_version = \">= 1.3\""] + block("required_providers", block("azurerm =", attributes([
        ("source", string("hashicorp/azurerm")), ("version", string(AZURE_PROVIDER))]))))  # fmt: skip
    out += [""] + block('provider "azurerm"', ["features {}", "subscription_id = var.subscription_id"])
    out += [""] + block('variable "subscription_id"', attributes([
        ("description", string("The subscription (azurerm 4 and later need it here or in ARM_SUBSCRIPTION_ID)")), ("type", "string"),
        ("default", "null")]))  # fmt: skip
    out += [""] + block('variable "resource_group_name"', attributes([("description", string("The resource group to create the groups in")),
                                                                       ("type", "string")]))  # fmt: skip
    out += [""] + block('variable "location"', attributes([("description", string("Their location; the resource group's when not given")),
                                                           ("type", "string"), ("default", "null")]))  # fmt: skip
    out += [""] + block('data "azurerm_resource_group" "target"', ["name = var.resource_group_name"])
    taken: Set[str] = set()
    asgs: Dict[str, str] = {}  # name -> data source
    resources = [r for r in template.get("resources", []) if isinstance(r, dict)]
    for resource in resources:
        for rule in resource.get("properties", {}).get("securityRules", []):
            for side in ("source", "destination"):
                for item in rule.get("properties", {}).get(f"{side}ApplicationSecurityGroups", []):
                    found = _RESOURCE_ID.match(str(item.get("id", "")))
                    if found and found.group(1).replace("''", "'") not in asgs:
                        name = found.group(1).replace("''", "'")
                        asgs[name] = identifier("asg_" + name, taken, "asg")
    for name, data in asgs.items():
        out += [""] + block(f'data "azurerm_application_security_group" "{data}"', attributes([
            ("name", string(name)), ("resource_group_name", "var.resource_group_name")]))  # fmt: skip
    names: Dict[str, str] = {}
    for resource in resources:
        nsg = str(resource.get("name", "nsg"))
        names[nsg] = identifier("nsg_" + nsg, taken, "nsg")
        out += [""]
        if nsg in networks:
            out.append(comment(f"associate {nsg} with the subnets of: {' '.join(networks[nsg]) or '(no networks)'}"))
        lines = attributes([("name", string(nsg)), ("location", "coalesce(var.location, data.azurerm_resource_group.target.location)"),
                            ("resource_group_name", "var.resource_group_name")])  # fmt: skip
        lines += block("tags =", [f"generator = {string('FWShift')}"])
        for rule in resource.get("properties", {}).get("securityRules", []):
            body = rule.get("properties", {})
            pairs: List[Tuple[str, str]] = [("name", string(str(rule.get("name", ""))))]
            for arm, hcl in _AZURE_FIELDS:
                if arm in body:
                    pairs.append((hcl, value(body[arm])))
            for side in ("source", "destination"):
                ids = []
                for item in body.get(f"{side}ApplicationSecurityGroups", []):
                    found = _RESOURCE_ID.match(str(item.get("id", "")))
                    ids.append(f"data.azurerm_application_security_group.{asgs[found.group(1).replace(chr(39) * 2, chr(39))]}.id"
                               if found else string(str(item.get("id", ""))))  # fmt: skip
                if ids:
                    pairs.append((f"{side}_application_security_group_ids", "[" + ", ".join(ids) + "]"))
            lines += [""] + block("security_rule", attributes(pairs))
        out += block(f'resource "azurerm_network_security_group" "{names[nsg]}"', lines)
    out += [""] + block('output "fwshift_networks"', [f"description = {string('Each network security group, with the networks of the subnets to associate it with')}"]
                        + block("value =", [line for nsg, ident in names.items() for line in block(f"{string(nsg)} =", attributes([
                            ("id", f"azurerm_network_security_group.{ident}.id"), ("networks", value(networks.get(nsg, [])))]))]))  # fmt: skip
    not_written = metadata.get("notWritten", [])
    if not_written:
        out += ["", "# Not written:"] + [comment(f"  {line}") for line in not_written]
    return "\n".join(out) + "\n"


# -- Google Cloud ------------------------------------------------------------------------------

GOOGLE_PROVIDER = ">= 5.0"


def emit_terraform_google(policy: Policy, report: Report, options: Options) -> str:
    found = emit_gcp.plan(policy, report, options)
    name = emit_gcp.policy_name(options)
    report.note(
        Severity.REVIEW, "TERRAFORM_LOAD",
        "the output is Terraform configuration (section 10): terraform plan -var project=... shows what it creates, terraform apply "
        f"creates a new global network firewall policy ({name}) with its rules; a policy of the same name makes it fail. It is "
        "associated with no network: nothing changes until it is (google_compute_network_firewall_policy_association)",
    )  # fmt: skip
    report.note(
        Severity.REVIEW, "GCP_ORDER",
        "the policy decides every connection of the network it is associated with: it ends in the default of the source. With "
        "the network's enforcement order AFTER_CLASSIC_FIREWALL (the default) the VPC firewall rules of the network decide "
        "first; set network_firewall_policy_enforcement_order = \"BEFORE_CLASSIC_FIREWALL\" on the network, or remove its VPC "
        "firewall rules",
    )  # fmt: skip
    out = header("a Google Cloud network firewall policy (hashicorp/google)", [
        "  terraform init",
        "  terraform plan -var project=...      shows what would be created",
        "  terraform apply -var project=...     creates the policy and its rules",
        "",
        "The policy is associated with no network: nothing changes for any traffic until you associate it (the commented",
        "resource at the end). It decides every connection of that network; with the network's enforcement order",
        "AFTER_CLASSIC_FIREWALL (the default) the VPC firewall rules decide first. A policy of the same name makes the apply fail.",
    ])
    out += [""] + block("terraform", ["required_version = \">= 1.3\""] + block("required_providers", block("google =", attributes([
        ("source", string("hashicorp/google")), ("version", string(GOOGLE_PROVIDER))]))))  # fmt: skip
    out += [""] + block('variable "project"', attributes([("description", string("The project to create the policy in")), ("type", "string")]))
    out += [""] + block('resource "google_compute_network_firewall_policy" "policy"', attributes([
        ("name", string(name)), ("project", "var.project"),
        ("description", string("Generated by FWShift; review the conversion report before associating it"))]))  # fmt: skip
    for rule in found.rules:
        pairs: List[Tuple[str, str]] = [("project", "var.project"), ("firewall_policy", "google_compute_network_firewall_policy.policy.name"),
                                        ("priority", str(rule.priority)), ("direction", string(rule.direction)), ("action", string(rule.action))]  # fmt: skip
        if rule.disabled:
            pairs.append(("disabled", "true"))
        if rule.log:
            pairs.append(("enable_logging", "true"))
        if rule.description:
            pairs.append(("description", string(rule.description[:1000])))
        match = attributes([("src_ip_ranges", value(rule.sources)), ("dest_ip_ranges", value(rule.destinations))])
        for protocol, ports in rule.layer4:
            match += block("layer4_configs", attributes([("ip_protocol", string(protocol))] + ([("ports", value(ports))] if ports else [])))
        out += [""] + block(f'resource "google_compute_network_firewall_policy_rule" "r{rule.priority}"', attributes(pairs) + block("match", match))
    out += ["", "# Associate the policy with the network when you are ready:", "#",
            '# resource "google_compute_network_firewall_policy_association" "fwshift" {',
            f"#   name              = {string(name + '-association')}",
            "#   project           = var.project",
            "#   firewall_policy   = google_compute_network_firewall_policy.policy.id",
            '#   attachment_target = "projects/PROJECT/global/networks/NETWORK"',
            "# }"]  # fmt: skip
    if found.not_written:
        out += ["", "# Not written:"] + [comment(f"  {line}") for line in found.not_written]
    return "\n".join(out) + "\n"
