class _Emitter:
    def __init__(self, p: Policy, report: Report, options: Options, source_zones: Set[str], rules: NameRules) -> None:
        self.p, self.report, self.options, self.rules = p, report, options, rules
        self.source_zones = source_zones  # zone names of the rules before --zone-map
        self.native = p.vendor == "checkpoint"
        self.prefix = options.object_prefix
        self.layer = options.target_layer or "Network"
        self.package = options.target_package or "Standard"
        # A predefined object of a Check Point source exists on the target as it is, whatever its type.
        self.kept = _existing(p) if self.native else set()
        self.taint_a = transform.tainted_addresses(p, keep=self.kept)
        self.taint_s: Dict[str, str] = {}
        for kind, names in (
            ("address", p.addresses), ("address-group", p.address_groups),
            ("service", p.services), ("service-group", p.service_groups),
        ):  # fmt: skip
            for name in names:
                item = report.items.get((kind, name))
                if name in self.kept and item is not None and item.findings:
                    # Whatever the parser could not read of it: the target has the very same object.
                    item.findings = [
                        f for f in item.findings if not f.code.startswith("UNSUPPORTED_") and f.code != "GATEWAY_OBJECT"
                    ]
                    report.add(
                        kind, name, Severity.INFO, "EXISTING_OBJECT",
                        "an object the management server has already (predefined, or a gateway): referenced by "
                        "name, not created",
                    )  # fmt: skip
        if self.native:
            report.retract("rule", {"GATEWAY_OBJECT"})
        self.lines: List[str] = []
        self.zones = _zones(p, options)
        self.taken: Set[str] = (
            set(p.addresses) | set(p.address_groups) | set(p.services) | set(p.service_groups) | set(self.zones)
        )
        self.address_ref: Dict[str, str] = {}  # model address or group -> Check Point object
        self.service_ref: Dict[str, str] = {}  # model service or group -> Check Point object or group
        self.single_service: Dict[str, ServiceEntry] = {}  # services that are one Check Point object
        self.literals: Dict[Tuple[Interval, bool], str] = {}  # (addresses, written as a range) -> object
        self.by_value: Dict[Interval, str] = {}  # addresses a literal can be written with
        self.domains: Dict[str, str] = {}
        self.app_services: Dict[str, str] = {}
        self.port_services: Dict[Tuple[str, str], str] = {}
        self.position = 0
        self.nat_written = 0
        self.used_zones: List[str] = []
        self.layer_count = 0

    def cmd(self, *words: str) -> None:
        # Every add takes ignore-warnings: a management server warns where an object repeats a port or address another
        # object already has ("The port is already used by another service": tcp/22 of its own `ssh`, R82.20) and then
        # refuses the call, though the object is the one the policy needs. Errors (a name taken) still stop the script.
        if words and words[0].split()[0] == "add":
            words = (*words, "ignore-warnings", "true")
        self.lines.append("m " + " ".join(words))

    def comment(self, text: str) -> None:
        self.lines += ["", "# " + " ".join(text.split())]

    # -- objects ----------------------------------------------------------

    def _new_name(self, label: str) -> str:
        """Name for an object the converter adds; kept to characters every release accepts."""
        return unique(self.prefix + label, self.taken, CHECKPOINT)

    def _address_object(self, name: str, interval: Interval, is_range: bool, comment: str = "") -> None:
        version, first, last = interval
        tail = ["comments", _text(comment)] if comment else []
        if first == last:
            self.cmd("add host name", q(name), "ip-address", str(int_to_ip(version, first)), *tail)
            return
        networks = list(ipaddress.summarize_address_range(int_to_ip(version, first), int_to_ip(version, last)))
        whole = interval in (FULL_V4, FULL_V6)  # a network of prefix length 0 is not accepted as an object
        if is_range or whole or len(networks) != 1:
            self.cmd(
                "add address-range name", q(name), "ip-address-first", str(int_to_ip(version, first)),
                "ip-address-last", str(int_to_ip(version, last)), *tail,
            )  # fmt: skip
            return
        subnet, _, length = str(networks[0]).partition("/")
        self.cmd("add network name", q(name), "subnet", subnet, "mask-length", length, *tail)

    def _placeholder(self, kind: str, name: str, reason: str) -> None:
        """An empty group: it keeps references valid and matches nothing."""
        self.cmd(f"add {kind} name", q(name), "comments", _text(_PLACEHOLDER + reason))

    def _addresses(self) -> None:
        self.comment("Network objects")
        for address in self.p.addresses.values():
            name = address.name
            self.address_ref[name] = name
            if address.builtin == "checkpoint" and self.native:
                continue
            if address.kind == AddressKind.UNSUPPORTED:
                self._placeholder("group", name, address.raw or "unsupported address type")
            elif address.kind == AddressKind.FQDN:
                # A domain object is named after the domain itself, with a leading dot.
                domain = "." + address.value.strip().strip(".")
                if domain not in self.domains:
                    self.domains[domain] = domain
                    self.taken.add(domain)
                    self.cmd("add dns-domain name", q(domain), "is-sub-domain false")
                self.address_ref[name] = domain
                self.taken.discard(name)
            else:
                interval = parse_literal(address.value)
                if interval is None:
                    self._placeholder("group", name, f"unreadable address '{address.value}'")
                    self.taint_a[name] = f"unreadable address '{address.value}'"
                else:
                    self._address_object(name, interval, address.kind == AddressKind.RANGE, address.description)
                    self.by_value.setdefault(interval, name)
        for group in transform.topo_groups(self.p.address_groups):
            self.address_ref[group.name] = group.name
            if group.builtin == "checkpoint" and self.native:
                continue
            if transform.is_placeholder_group(group):
                self._placeholder("group", group.name, self.taint_a.get(group.name, "unconvertible group"))
                continue
            members = transform.dedupe([self._member(member) for member in group.members])
            words = [f"members.{index} {q(member)}" for index, member in enumerate(members, 1)]
            tail = ["comments", _text(group.description)] if group.description else []
            self.cmd("add group name", q(group.name), *words, *tail)

    def _member(self, member: str) -> str:
        """Check Point object for a rule or group member; a literal gets an object of its own."""
        if member in self.address_ref:
            return self.address_ref[member]
        interval = parse_literal(member)
        if interval is None:
            return member
        if interval in self.by_value:
            return self.by_value[interval]  # an object of the source says the same
        is_range = "-" in member and "/" not in member and interval[1] != interval[2]
        if (interval, is_range) not in self.literals:
            if interval == FULL_V4 or interval == FULL_V6:
                label = "All-IPv4" if interval == FULL_V4 else "All-IPv6"
            elif interval[1] == interval[2]:
                label = f"h-{int_to_ip(interval[0], interval[1])}"
            elif is_range:
                label = f"r-{member}"
            else:
                net = ipaddress.ip_network(member.strip(), strict=False)
                label = f"n-{net.network_address}_{net.prefixlen}"
            name = self._new_name(label)
            self._address_object(name, interval, is_range)
            self.literals[(interval, is_range)] = name
        return self.literals[(interval, is_range)]

    # -- services ---------------------------------------------------------

    @staticmethod
    def _pieces(entries: List[ServiceEntry]) -> List[Tuple[str, List[str], ServiceEntry]]:
        """(label, mgmt_cli words around the name, what it matches) for each Check Point service object.

        An entry for every IP protocol has no object and yields nothing: the caller rules it out first.
        """
        out: List[Tuple[str, List[str], ServiceEntry]] = []
        for entry in entries:
            proto = entry.protocol
            if proto in L4_PROTOCOLS:
                for source in entry.src_ports.split(",") if entry.src_ports else [""]:
                    for port in (entry.dst_ports or "1-65535").split(","):
                        words = [f"add service-{proto.value} name", "port", port]
                        words += ["source-port", source] if source else []
                        words += ["match-for-any false"] if proto != Protocol.SCTP else []
                        label = f"{proto.value}{port}" + (f"-from{source}" if source else "")
                        out.append((label, words, ServiceEntry(proto, port, source)))
            elif proto in (Protocol.ICMP, Protocol.ICMP6):
                number, kind = (1, "service-icmp") if proto == Protocol.ICMP else (58, "service-icmp6")
                if entry.icmp_type is None:
                    words = ["add service-other name", "ip-protocol", str(number), "match-for-any false"]
                    out.append((proto.value, words, entry))
                    continue
                words = [f"add {kind} name", "icmp-type", str(entry.icmp_type)]
                label = f"{proto.value}-type{entry.icmp_type}"
                if entry.icmp_code is not None:
                    words += ["icmp-code", str(entry.icmp_code)]
                    label += f"-code{entry.icmp_code}"
                out.append((label, words, entry))
            elif entry.ip_protocol is not None:
                words = ["add service-other name", "ip-protocol", str(entry.ip_protocol), "match-for-any false"]
                out.append((f"ip{entry.ip_protocol}", words, entry))
        return out

    def _define_service(self, name: str, entries: List[ServiceEntry], comment: str = "") -> None:
        """Write one service object, or several and a group."""
        pieces = self._pieces(entries)
        if not pieces:
            self._placeholder("service-group", name, "no protocol or port to match")
            return
        tail = ["comments", _text(comment)] if comment else []
        if len(pieces) == 1:
            _, words, entry = pieces[0]
            self.cmd(words[0], q(name), *words[1:], *tail)
            self.single_service[name] = entry
            return
        members: List[str] = []
        for label, words, _ in pieces:
            member = unique(f"{name}-{label}", self.taken, CHECKPOINT)
            self.cmd(words[0], q(member), *words[1:])
            members.append(member)
        listed = [f"members.{index} {q(member)}" for index, member in enumerate(members, 1)]
        self.cmd("add service-group name", q(name), *listed, *tail)

    def _services(self) -> None:
        self.comment("Services")
        bad: Dict[str, str] = {}
        referenced = {member for rule in self.p.rules for member in rule.services}
        referenced |= {nat.service for nat in self.p.nat_rules}
        referenced |= {member for group in self.p.service_groups.values() for member in group.members}
        for service in self.p.services.values():
            name = service.name
            self.service_ref[name] = name
            if service.builtin == "checkpoint" and self.native:
                if len(service.entries) == 1:
                    self.single_service[name] = service.entries[0]
                continue
            if not service.entries or service.unsupported:
                self._placeholder("service-group", name, service.unsupported or "unsupported or undefined service")
            elif any(e.protocol == Protocol.IP and e.ip_protocol is None for e in service.entries):
                # "Every protocol" is the Any of a rule, not an object. Nothing is written unless it is used.
                bad[name] = "a service that matches every IP protocol cannot be an object"
                if name in referenced:
                    self._placeholder("service-group", name, bad[name])
            else:
                self._define_service(name, service.entries, service.description)
        self.taint_s = transform.tainted_services(self.p, bad, keep=self.kept)
        for group in transform.topo_groups(self.p.service_groups):
            self.service_ref[group.name] = group.name
            if group.builtin == "checkpoint" and self.native:
                continue
            if not group.members:
                self._placeholder("service-group", group.name, "empty service group")
                continue
            words = [f"members.{index} {q(member)}" for index, member in enumerate(transform.dedupe(group.members), 1)]
            tail = ["comments", _text(group.description)] if group.description else []
            self.cmd("add service-group name", q(group.name), *words, *tail)

    def _app_service(self, app: str, entries: List[ServiceEntry]) -> str:
        if app not in self.app_services:
            name = self._new_name(f"app-{app}")
            self._define_service(name, entries, f"well-known ports of application {app}")
            self.app_services[app] = name
        return self.app_services[app]

    def _port_service(self, protocol: Protocol, port: str) -> str:
        """Service object for a translated port."""
        key = (protocol.value, port)
        if key not in self.port_services:
            wanted = ServiceEntry(protocol, port)
            existing = [name for name, entry in self.single_service.items() if entry == wanted]
            if existing:
                self.port_services[key] = existing[0]
            else:
                self.port_services[key] = self._new_name(f"{protocol.value}-{port}")
                self._define_service(self.port_services[key], [wanted])
        return self.port_services[key]

    # -- security rules ---------------------------------------------------

    def _row(self, rule: Rule) -> _Row:
        report = self.report
        transform.note_profiles(report, rule)
        reasons = transform.blocking_reasons(rule, self.taint_a, self.taint_s)
        if rule.users != [ANY]:
            reasons.append(("USER_MATCH", "source user match " + ", ".join(rule.users) + " is not converted"))
        if rule.url_categories != [ANY]:
            reasons.append(
                ("URL_CATEGORY", "URL category match " + ", ".join(rule.url_categories) + " is not converted")
            )
        transform.note_fqdn_families(self.p, rule, report, "Check Point")
        lowered = transform.lower_applications(rule, self.options.app_ports, report, reasons)
        if lowered is None:
            services = [] if ANY in rule.services else [self.service_ref.get(s, s) for s in rule.services]
        else:
            services = [self._app_service(app, entries) for app, entries in lowered]
        sources = [] if ANY in rule.sources else transform.dedupe([self._member(m) for m in rule.sources])
        destinations = [] if ANY in rule.destinations else transform.dedupe([self._member(m) for m in rule.destinations])
        for cell, negated, what in (
            (sources, rule.negate_source, "source"),
            (destinations, rule.negate_destination, "destination"),
            (services, rule.negate_service, "service"),
        ):
            if negated and not cell:
                reasons.append(("NEGATED_ANY", f"a negated 'any' {what} matches nothing"))
        if rule.action in _ACTIONS:
            action = _ACTIONS[rule.action]
        else:
            action = "Reject"
            if rule.action != Action.RESET_CLIENT:
                report.add(
                    "rule",
                    rule.origin,
                    Severity.INFO,
                    "RESET_ACTION",
                    f"action {rule.action.value} becomes Reject, which answers the client only",
                )
        if rule.scope != RuleScope.UNIVERSAL and ANY in rule.src_zones and ANY in (
            rule.src_zones if rule.scope == RuleScope.INTRAZONE else rule.dst_zones
        ):
            report.add(
                "rule",
                rule.origin,
                Severity.REVIEW,
                "RULE_TYPE_ANY_ZONE",
                f"{rule.scope.value} rule for 'any' zone: it is written for the zones the policy names. Traffic "
                "between interfaces whose zones no rule names cannot be told to be inside one zone or between two: "
                + ("it is not allowed by this rule" if rule.action == Action.ALLOW else "this rule blocks all of it"),
            )
        if reasons:
            transform.disable_rule(report, rule, reasons)
        return _Row(rule, sources, destinations, services, action, bool(reasons) or not rule.enabled, bool(reasons))

    def _write_rule(self, row: _Row, layer: str, position: str) -> None:
        rule = row.rule
        words = ["add access-rule layer", q(layer), "position", position, "name", _text(rule.name)]
        # A rule that stands alone carries its zones in its own cells; otherwise the layer has matched them.
        sources = row.sources or (row.src_zones if row.standalone else [])
        destinations = row.destinations or (row.dst_zones if row.standalone else [])
        for column, members in (("source", sources), ("destination", destinations), ("service", row.services)):
            words += _cell(column, members)
        if rule.negate_source:
            words.append("source-negate true")
        if rule.negate_destination:
            words.append("destination-negate true")
        if rule.negate_service:
            words.append("service-negate true")
        words += ["action", row.action, "track.type", "Log" if rule.log_start or rule.log_end else "None"]
        if row.disabled:
            words.append("enabled false")
        text = ("FWSHIFT: disabled by the converter, see the report. " if row.flagged else "") + rule.description
        if text.strip():
            words += ["comments", _text(text)]
        self.cmd(*words)

    def _cleanup(self, layer: str, position: str, accept: bool, comment: str) -> None:
        self.cmd(
            "add access-rule layer", q(layer), "position", position, "name", q("FWShift cleanup"),
            *_cell("source", []), *_cell("destination", []), *_cell("service", []), "action", "Accept" if accept else "Drop", "track.type", "None" if accept else "Log", "comments", _text(comment),
        )  # fmt: skip

    def _applies(self, rule: Rule, src: Optional[str], dst: Optional[str]) -> bool:
        """Whether the rule can match traffic from zone ``src`` to zone ``dst``; None is any other zone."""
        src_ok = ANY in rule.src_zones or (src is not None and src in rule.src_zones)
        dst_ok = ANY in rule.dst_zones or (dst is not None and dst in rule.dst_zones)
        if rule.scope == RuleScope.UNIVERSAL:
            return src_ok and dst_ok
        if src is None and dst is None:
            # Two zones the policy does not name: whether they are one zone or two cannot be told.
            # A deny is applied either way and an allow in neither case, and the rule is reported.
            both_ok = src_ok and (dst_ok or rule.scope == RuleScope.INTRAZONE)
            return both_ok and rule.action != Action.ALLOW
        if rule.scope == RuleScope.INTRAZONE:
            return src == dst and src_ok
        return src_ok and dst_ok and src != dst

    def _rules(self) -> None:
        rows = [self._row(rule) for rule in self.p.rules]
        # What no rule matches inside a zone, as the source decides it: the zone's own setting, or the policy's default;
        # a zone --zone-map makes of several is open only where the source also allows between them.
        decided = transform.intrazone_decisions(self.p, self.options.zone_map, self.source_zones, self.zones, self.report)
        open_zones = {zone for zone in self.zones if decided[zone]}

        def signature(src: Optional[str], dst: Optional[str]) -> Signature:
            """What decides whether traffic from ``src`` to ``dst`` needs a layer of its own."""
            indexes = tuple(
                i for i, row in enumerate(rows) if not row.standalone and self._applies(row.rule, src, dst)
            )
            return indexes, "accept" if src is not None and src == dst and src in open_zones else "drop"

        def content(src: Optional[str], dst: Optional[str]) -> List[int]:
            """Rules of the layer for this traffic. A rule that stands alone matches its zones itself,
            so it is left out only where a zone the layer has fixed rules it out."""
            out: List[int] = []
            for i, row in enumerate(rows):
                if not row.standalone:
                    keep = self._applies(row.rule, src, dst)
                else:
                    keep = (src is None or not row.src_zones or src in row.src_zones) and (
                        dst is None or not row.dst_zones or dst in row.dst_zones
                    )
                if keep:
                    out.append(i)
            return out

        top = signature(None, None)
        from_zone = {zone: signature(zone, None) for zone in self.zones}
        to_zone = {zone: signature(None, zone) for zone in self.zones}
        classes: List[Tuple[Optional[str], Optional[str], str]] = []
        for zone_a in self.zones:
            for zone_b in self.zones:
                # Without a layer of its own, traffic of this pair reaches the first of these that exists.
                if from_zone[zone_a] != top:
                    fallback = from_zone[zone_a]
                elif to_zone[zone_b] != top:
                    fallback = to_zone[zone_b]
                else:
                    fallback = top
                if signature(zone_a, zone_b) != fallback:
                    classes.append((zone_a, zone_b, signature(zone_a, zone_b)[1]))
        classes += [(zone, None, from_zone[zone][1]) for zone in self.zones if from_zone[zone] != top]
        classes += [(None, zone, to_zone[zone][1]) for zone in self.zones if to_zone[zone] != top]

        top_rows = content(None, None)
        used = [zone for src, dst, _ in classes for zone in (src, dst) if zone is not None]
        used += [zone for row in rows if row.standalone for zone in row.src_zones + row.dst_zones]
        self.used_zones = transform.dedupe(used)
        self.layer_count = len(classes)
        missing = [zone for zone in self.used_zones if zone not in _PREDEFINED_ZONES]
        if missing:
            self.comment("Security zones")
            self.lines += [f"zone {q(zone)}" for zone in missing]
        placed: Dict[int, List[str]] = {}
        for src, dst, tail in classes:
            name = unique(f"{self.layer}_{src or 'any'}_to_{dst or 'any'}", self.taken, CHECKPOINT)
            self.comment(f"Traffic from zone {src or '(any other)'} to zone {dst or '(any other)'}")
            self.cmd("add access-layer name", q(name), "add-default-rule false")
            indexes = content(src, dst)
            self._fill(name, [rows[i] for i in indexes], tail, numbered=False)
            for index in indexes:
                placed.setdefault(index, []).append(f"layer {name}")
            self.position += 1
            words = ["add access-rule layer", q(self.layer), "position", str(self.position)]
            words += ["name", _text(f"{src or 'any'} to {dst or 'any'}")]
            words += _cell("source", [src] if src else []) + _cell("destination", [dst] if dst else [])
            words += _cell("service", [])
            self.cmd(*words, "action", q("Apply Layer"), "inline-layer", q(name))
        self.comment(f"Rules of layer {self.layer}" + (" for traffic of no zone pair above" if classes else ""))
        self._fill(self.layer, [rows[i] for i in top_rows], top[1], numbered=True)
        for index in top_rows:
            placed.setdefault(index, []).append(f"layer {self.layer}")
        for index, row in enumerate(rows):
            item = self.report.item("rule", row.rule.origin)
            where = placed.get(index, [])
            if not where:
                unknown = ANY in row.rule.src_zones + row.rule.dst_zones
                self.report.skip(
                    "rule",
                    row.rule.origin,
                    "RULE_TYPE_EMPTY",
                    f"{row.rule.scope.value} rule whose zones leave no pair of zones it applies to: not written",
                    Severity.REVIEW if unknown else Severity.INFO,
                )
            else:
                item.emitted_as += [row.rule.name] if where == [f"layer {self.layer}"] else where

    def _fill(self, layer: str, rows: List[_Row], tail: str, numbered: bool) -> None:
        """Write the rules of one layer, in order, and close it."""

        def position() -> str:
            if not numbered:
                return "bottom"
            self.position += 1
            return str(self.position)

        for row in rows:
            self._write_rule(row, layer, position())
        if rows and rows[-1].catch_all:
            return  # the rules end in one that matches everything
        if tail == "accept":
            self._cleanup(layer, position(), True, "Added by FWShift: the source allows traffic inside this zone that no rule denies.")
        else:
            self._cleanup(layer, position(), False, "Added by FWShift: the source drops what no rule allows.")

    # -- NAT --------------------------------------------------------------

    def _cell(self, nat: NatRule, members: List[str], suffix: str) -> Optional[str]:
        """Object for a NAT cell, which holds one object: several members become a group."""
        if ANY in members:
            return None
        names = transform.dedupe([self._member(member) for member in members])
        if len(names) == 1:
            return names[0]
        name = self._new_name(f"{nat.name}-{suffix}")
        self.cmd("add group name", q(name), *[f"members.{i} {q(member)}" for i, member in enumerate(names, 1)])
        self.report.add(
            "nat", nat.origin, Severity.INFO, "NAT_GROUP", f"group '{name}' created: a NAT rule cell holds one object"
        )
        return name

    def _single_address(self, ref: str) -> Optional[Interval]:
        intervals = transform.address_intervals(self.p, ref)
        return intervals[0] if intervals and len(intervals) == 1 else None

    def _nat(self, nat: NatRule) -> None:
        report = self.report
        source, destination = nat.source_translation, nat.destination_translation
        members = nat.sources + nat.destinations
        members = members + (source.addresses if source else []) + ([destination.address] if destination else [])
        problems = list(nat.unsupported)
        problems += [f"references '{m}': {self.taint_a[m]}" for m in members if m in self.taint_a]
        if nat.service in self.taint_s:
            problems.append(f"references '{nat.service}': {self.taint_s[nat.service]}")
        service = self.single_service.get(nat.service)
        if nat.service != ANY and service is None and not problems:
            problems.append(f"service '{nat.service}' is not a single protocol and port; a NAT rule takes one service")
        # Decide first, write afterwards: nothing is created for a rule that is not written.
        method = "static"
        hide_behind = ""  # address or object the source is translated to
        gateway = ""
        findings: List[Tuple[Severity, str, str]] = []
        if source is not None and not problems:
            kind = source.kind
            if kind == SnatKind.INTERFACE:
                method = "hide"
                if source.addresses:
                    hide_behind = source.addresses[0]
                    if hide_behind not in self.p.addresses:
                        hide_behind = hide_behind.split("/")[0]  # PAN-OS writes an interface address with its mask
                elif self.options.target_gateway or (self.native and source.interface):
                    # A Check Point source names the gateway object it hides behind.
                    gateway = self.options.target_gateway or source.interface
                elif source.interface_address:
                    hide_behind = source.interface_address
                    findings.append(
                        (Severity.APPROX, "NAT_INTERFACE_ADDRESS", f"hides behind {hide_behind}, the address "
                         f"interface '{source.interface}' has today; name the gateway object with --target-gateway "
                         "to hide behind the gateway instead")  # fmt: skip
                    )
                else:
                    problems.append(
                        "source NAT to the address of the outgoing interface; name the gateway object to hide "
                        "behind with --target-gateway"
                    )
            elif kind == SnatKind.DYNAMIC_PORT:
                method = "hide"
                pool = self._single_address(source.addresses[0]) if len(source.addresses) == 1 else None
                if pool is None or size(pool) != 1:
                    problems.append("hide NAT is written behind one address; this rule translates to several")
                else:
                    hide_behind = source.addresses[0]
            elif kind == SnatKind.STATIC:
                inside = self._single_address(nat.sources[0]) if len(nat.sources) == 1 else None
                outside = self._single_address(source.addresses[0]) if len(source.addresses) == 1 else None
                if inside is None or outside is None or size(inside) != size(outside):
                    problems.append("static NAT needs one source and one translated object of the same size")
                else:
                    hide_behind = source.addresses[0]
            else:
                problems.append("dynamic NAT without port translation has no Check Point equivalent")
        port = destination.port if destination is not None else ""
        if port and not problems:
            if service is None or service.protocol not in L4_PROTOCOLS:
                problems.append("a port translation needs a TCP, UDP or SCTP service on the rule")
            elif not is_number(port):
                problems.append(f"translated port '{port}' is not a single port")
        if problems:
            report.skip("nat", nat.origin, "NAT_NOT_CONVERTED", "not converted: " + "; ".join(problems))
            return
        # Zones are left out. With explicit addresses on that side a zone adds little; where the
        # addresses are "any", the zone was the only limit.
        if nat.src_zones != [ANY]:
            unlimited = ANY in nat.sources and ANY in nat.destinations
            findings.append(
                (Severity.REVIEW if unlimited else Severity.APPROX, "NAT_ZONES", "the rule applied to traffic from "
                 + ", ".join(nat.src_zones) + " only; it is written without zones and applies whatever the zone "
                 "the traffic comes from")  # fmt: skip
            )
        if nat.dst_zones != [ANY]:
            unlimited = ANY in nat.destinations
            findings.append(
                (Severity.REVIEW if unlimited else Severity.APPROX, "NAT_ZONES", "the rule applied to traffic to "
                 + ", ".join(nat.dst_zones) + " only; it is written without zones"
                 + (" and now translates traffic towards every other zone as well: put a rule without translation "
                    "above it for the traffic that must keep its addresses" if unlimited else ""))  # fmt: skip
            )
        for severity, code, message in findings:
            report.add("nat", nat.origin, severity, code, message)

        words: List[str] = []
        original_source = self._cell(nat, nat.sources, "src")
        original_destination = self._cell(nat, nat.destinations, "dst")
        words += ["original-source", q(original_source)] if original_source else []
        words += ["original-destination", q(original_destination)] if original_destination else []
        words += ["original-service", q(self.service_ref[nat.service])] if nat.service != ANY else []
        if gateway or hide_behind:
            words += ["translated-source", q(gateway or self._member(hide_behind))]
        if destination is not None:
            words += ["translated-destination", q(self._member(destination.address))]
            if port and service is not None:
                words += ["translated-service", q(self._port_service(service.protocol, port))]
        state = [] if nat.enabled else ["enabled false"]
        note = nat.name + (f": {nat.description}" if nat.description else "")
        head = ["add nat-rule package", q(self.package), "position bottom"]
        self.cmd(*head, *_nat_cells(words), "method", method, *state, "comments", _text(note))
        self.nat_written += 1
        if source is not None and source.kind == SnatKind.STATIC and source.bidirectional:
            # The inbound half: traffic to the translated address goes to the real one.
            back = ["original-destination", q(self._member(source.addresses[0]))]
            back += ["translated-destination", q(self._member(nat.sources[0]))]
            self.cmd(*head, *_nat_cells(back), "method static", *state, "comments", _text(nat.name + " (inbound)"))
            report.add(
                "nat", nat.origin, Severity.INFO, "NAT_BIDIRECTIONAL",
                "bi-directional static NAT written as two rules, one for each direction",
            )  # fmt: skip

    # -- output -----------------------------------------------------------

    def run(self) -> str:
        self._addresses()
        self._services()
        self._rules()
        if self.p.nat_rules:
            self.comment(f"NAT rules of package {self.package}")
            for nat in self.p.nat_rules:
                self._nat(nat)
            written = {nat.origin for nat in self.p.nat_rules if not self.report.item("nat", nat.origin).skipped}
            transform.note_nat_order(self.p, self.report, written, "first-match")
        self._notes()
        header = HEADER.format(layer=self.layer, package=self.package)
        return header + "\n".join(self.lines) + "\n\necho 'Done. Review the session, then publish or discard it.'\n"

    def _notes(self) -> None:
        note = self.report.note
        note(
            Severity.REVIEW,
            "CHECKPOINT_SCRIPT",
            "the output is a shell script of mgmt_cli calls. It changes one session and publishes nothing: log in, "
            "run it, review the session in SmartConsole, then publish and install the policy yourself. It stops at "
            "the first call the server refuses; discard the session before running it again",
        )
        if not self.native:
            note(
                Severity.REVIEW,
                "IMPLIED_RULES",
                "Check Point applies implied rules (Global Properties) next to the rulebase, and every ordered "
                "layer of the policy package must accept a connection. Neither is part of the conversion: check "
                "that they allow no more and no less than intended",
            )
        note(
            Severity.INFO,
            "LAYER_PLACEMENT",
            f"the rules are written to the top of access layer '{self.layer}', in order, and end in a cleanup rule; "
            "rules the layer held before stay below it and are no longer reached. Choose another layer with "
            "--target-layer",
        )
        if self.used_zones:
            layers = (
                f" Rules that name a zone and addresses on the same side are sorted into {self.layer_count} inline "
                "layers, one per pair of zones."
                if self.layer_count
                else ""
            )
            note(
                Severity.REVIEW,
                "ZONES_REQUIRED",
                "the rules use these security zones, which must be assigned to the interfaces of the gateway (or "
                "renamed with --zone-map): " + ", ".join(self.used_zones) + "." + layers + " An interface without "
                "a zone only reaches the rules that name no zone",
            )
        if self.p.default_interzone == Action.ALLOW:
            note(
                Severity.REVIEW,
                "INTERZONE_DEFAULT",
                "the source allows traffic that no rule matches. That default is not carried over: every layer "
                "written here ends in a drop. Add a final accept rule if it was intended",
            )
        if not self.native and not self.prefix:
            note(
                Severity.INFO,
                "NAME_COLLISIONS",
                "Check Point predefines several hundred objects (http, https, ssh, ...). If the script stops because "
                "a name exists already, convert again with --target-prefix to give every created object a prefix",
            )
        lowered: Dict[str, List[str]] = {}
        for name in sorted(self.taken):
            lowered.setdefault(name.lower(), []).append(name)
        twins = [" and ".join(names) for names in lowered.values() if len(names) > 1]
        if twins:
            note(
                Severity.INFO,
                "NAMES_DIFFER_BY_CASE",
                "these names differ only in upper and lower case, which a management server may take for one name "
                "(the script stops if it does): " + ", ".join(twins),
            )
        if self.prefix:
            note(Severity.INFO, "OBJECT_PREFIX", f"every object the script creates is named with the prefix '{self.prefix}'")
        if self.domains:
            note(
                Severity.INFO,
                "DOMAIN_OBJECTS",
                "host names are written as domain objects, named after the domain with a leading dot; the gateway "
                "needs DNS to enforce them: " + ", ".join(self.domains),
            )
        if self.nat_written:
            note(
                Severity.REVIEW,
                "NAT_MANUAL_RULES",
                f"{self.nat_written} NAT rules are written as manual rules at the bottom of the NAT rulebase, below "
                "the automatic ones. Manual NAT does not answer ARP for translated addresses: add proxy ARP on the "
                "gateway for every translated address that is not routed to it",
            )
        tagged = any(
            holder.tags for holder in list(self.p.rules) + list(self.p.nat_rules) + list(self.p.addresses.values())
        )
        if tagged and not self.native:
            note(Severity.INFO, "TAGS_NOT_CONVERTED", "tags of rules and objects are not converted")
        if any(m in (ANY_V4, ANY_V6) for r in self.p.rules for m in r.sources + r.destinations):
            note(
                Severity.INFO,
                "ANY_ONE_IP_VERSION",
                "'any address of one IP version' is written as a range object covering that version (All-IPv4, All-IPv6)",
            )
