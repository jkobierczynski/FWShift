"""Check Point emitter: neutral model -> a shell script of Management API calls (``mgmt_cli``).

Design rules:

* The script creates objects and rules in the session it is given and stops at
  the first call the server refuses. It never publishes and never installs.
* Check Point rules have no zone columns. A zone object can stand in a source
  or destination cell, but a cell that lists a zone next to addresses means
  "either". A rule that names a zone and addresses on the same side is
  therefore written into an inline layer per pair of zones: the rule applying
  the layer matches the zones, the rules inside match the addresses.
* A layer written here ends in an explicit cleanup rule, so that nothing
  depends on the implicit cleanup action of a layer.
* Rules match the original packet, as the neutral model does: no destination
  is rewritten for NAT.
"""

