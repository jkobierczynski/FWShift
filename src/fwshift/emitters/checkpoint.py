_PLACEHOLDER = "FWSHIFT PLACEHOLDER, matches nothing: "
_BARE = re.compile(r"[A-Za-z0-9._/:=+-]+")
# Zones every Check Point management server has.
_PREDEFINED_ZONES: FrozenSet[str] = frozenset({"InternalZone", "ExternalZone", "DMZZone", "WirelessZone"})
# Names with a meaning of their own on Check Point; objects from another platform carrying one are renamed.
_RESERVED: FrozenSet[str] = frozenset({"Any", "Original", "None", "All_Internet", "Policy Targets"}) | _PREDEFINED_ZONES
_ACTIONS = {Action.ALLOW: "Accept", Action.DROP: "Drop", Action.DENY: "Drop"}
_COMMENT_LIMIT = 250

HEADER = """\
#!/bin/sh
# Generated by FWShift - review the conversion report before running this.
#
# Check Point Management API calls (mgmt_cli): objects, the rules of access layer
# '{layer}' and the NAT rules of policy package '{package}'.
#
# 1. Log in and keep the session in a file:
#        mgmt_cli login -r true > fwshift.sid          (as root on the management server)
#        mgmt_cli login user <admin> > fwshift.sid     (anywhere else; add -m <server>)
# 2. Run this script:  sh <this file>
# 3. Look at the session in SmartConsole. Nothing is published or installed here:
#        mgmt_cli publish -s fwshift.sid       to keep the changes
#        mgmt_cli discard -s fwshift.sid       to throw them away
#
# The script stops at the first call the server refuses. Discard the session, fix
# the cause and run it again: a policy with rules missing is not a safe policy.
#
# SID        session file (default fwshift.sid)
# MGMT_OPTS  extra switches for every call, for example: MGMT_OPTS='-m 192.0.2.10'

SID="${{SID:-fwshift.sid}}"

m() {{
    if ! out=$(mgmt_cli "$@" $MGMT_OPTS -s "$SID" 2>&1); then
        printf 'FAILED: mgmt_cli %s\\n%s\\n' "$*" "$out" >&2
        printf 'Stopped. Nothing was published. Undo with: mgmt_cli discard -s %s\\n' "$SID" >&2
        exit 1
    fi
}}

# A zone has no content of its own: one that exists already is used as it is.
zone() {{
    mgmt_cli show security-zone name "$1" $MGMT_OPTS -s "$SID" >/dev/null 2>&1 || m add security-zone name "$1" ignore-warnings true
}}
"""


def _cell(column: str, members: List[str]) -> List[str]:
    """The words that fill one cell of an access rule. An empty cell is written as Any: a cell the command leaves
    out is stored as None, which matches nothing (seen on R82.20)."""
    return [f"{column}.{index} {q(member)}" for index, member in enumerate(members or ["Any"], 1)]


_NAT_CELLS = (("original-source", "Any"), ("original-destination", "Any"), ("original-service", "Any"),
              ("translated-source", "Original"), ("translated-destination", "Original"),
              ("translated-service", "Original"))  # fmt: skip


def _nat_cells(words: List[str]) -> List[str]:
    """All six cells of a NAT rule, in order, each written out: what it names, or Any or Original."""
    given = dict(zip(words[0::2], words[1::2]))
    assert set(given) <= {column for column, _ in _NAT_CELLS}, words
    return [word for column, default in _NAT_CELLS for word in (column, given.get(column, default))]


def q(text: str) -> str:
    """Quote a value for the shell."""
    if _BARE.fullmatch(text) and not text.startswith("-"):
        return text
    return "'" + text.replace("'", "'\\''") + "'"


def _text(text: str) -> str:
    """A name or comment as one quoted word. mgmt_cli would read a leading hyphen as one of its switches."""
    cleaned = " ".join(text.split())[:_COMMENT_LIMIT]
    return q("_" + cleaned.lstrip("-") if cleaned.startswith("-") else cleaned)


def emit(policy: Policy, report: Report, options: Options) -> str:
    p = copy.deepcopy(policy)
    native = p.vendor == "checkpoint"
    rules = CHECKPOINT_NATIVE if native else CHECKPOINT
    source_zones = {z for r in list(p.rules) + list(p.nat_rules) for z in r.src_zones + r.dst_zones if z != ANY}
    options = dataclasses.replace(options, zone_map=_zone_names(p, options, source_zones, rules, report))
    transform.apply_zone_map(p, options.zone_map)
    transform.ensure_references(p, report)
    for option, value in (("--target-layer", options.target_layer), ("--target-package", options.target_package),
                          ("--target-gateway", options.target_gateway)):  # fmt: skip
        if clean(value, CHECKPOINT_NATIVE) != value and value:
            raise FwshiftError(f"{option} '{value[:40]}' is not a name mgmt_cli can be given")
    prefix = options.object_prefix
    if prefix:
        if CHECKPOINT.invalid.search(prefix) or len(prefix) > 20:
            raise FwshiftError("--target-prefix takes up to 20 letters, digits, periods, underscores and hyphens")
    # Check Point has one namespace for all objects: zones, addresses and services may not share a name.
    reserved = (frozenset() if native else _RESERVED) | set(_zones(p, options))
    existing = _existing(p) if native else set()
    transform.sanitize_names(
        p, rules, CHECKPOINT_NATIVE, report, reserved, reserved, one_namespace=True, prefix=prefix, keep=existing
    )
    if options.written is not None:
        options.written.append(p)
    return _Emitter(p, report, options, source_zones, rules).run()


def _existing(p: Policy) -> Set[str]:
    """Objects of a Check Point source that a Check Point target has already: predefined ones and gateways."""
    return (
        {n for n, a in p.addresses.items() if a.builtin == "checkpoint"}
        | {n for n, g in p.address_groups.items() if g.builtin == "checkpoint"}
        | {n for n, v in p.services.items() if v.builtin == "checkpoint"}
        | {n for n, w in p.service_groups.items() if w.builtin == "checkpoint"}
    )


def _zones(p: Policy, options: Options) -> List[str]:
    """Every zone the rules can tell apart, by its name on the target."""
    named = [z for r in p.rules for z in r.src_zones + r.dst_zones if z != ANY]
    defined = [options.zone_map.get(name, name) for name in p.zones]
    return transform.dedupe(named + defined)


def _zone_names(
    p: Policy, options: Options, source_zones: Set[str], rules: NameRules, report: Report
) -> Dict[str, str]:
    """--zone-map, extended so that every zone ends up with a name that can be an object name."""
    targets = {name: options.zone_map.get(name, name) for name in list(p.zones) + sorted(source_zones)}
    taken = {target for target in targets.values() if clean(target, rules) == target}
    renamed: Dict[str, str] = {}
    for target in targets.values():
        if target not in taken and target not in renamed:
            renamed[target] = unique(target, taken, rules)
    if renamed:
        report.note(
            Severity.INFO,
            "ZONE_RENAMED",
            "zone names that cannot be object names were changed (choose others with --zone-map): "
            + ", ".join(f"'{old}' to '{new}'" for old, new in renamed.items()),
        )
    out = dict(options.zone_map)
    out.update({name: renamed[target] for name, target in targets.items() if target in renamed})
    return out


@dataclass
class _Row:
    """One security rule, ready to be written into a layer."""

    rule: Rule
    sources: List[str]  # Check Point object names; empty means Any
    destinations: List[str]
    services: List[str]
    action: str
    disabled: bool
    flagged: bool  # disabled by the converter

    @property
    def src_zones(self) -> List[str]:
        return [] if ANY in self.rule.src_zones else self.rule.src_zones

    @property
    def dst_zones(self) -> List[str]:
        return [] if ANY in self.rule.dst_zones else self.rule.dst_zones

    @property
    def standalone(self) -> bool:
        """True when the cells of one rule can say all of it: no side needs a zone and addresses at once."""
        rule = self.rule
        return (
            rule.scope == RuleScope.UNIVERSAL
            and not (self.src_zones and (self.sources or rule.negate_source))
            and not (self.dst_zones and (self.destinations or rule.negate_destination))
        )

    @property
    def catch_all(self) -> bool:
        """True when the rule matches every packet that reaches it in the layer it is written to."""
        negated = self.rule.negate_source or self.rule.negate_destination or self.rule.negate_service
        if self.disabled or self.sources or self.destinations or self.services or negated:
            return False
        return not (self.standalone and (self.src_zones or self.dst_zones))


